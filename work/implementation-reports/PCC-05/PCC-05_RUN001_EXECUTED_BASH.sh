PCC-05 RUN 001
LAYERED MEMORY — STRUCTURAL ANATOMY

CANONICAL NEED

The epistemic organism must preserve increasing amounts of project
knowledge without requiring all history in active cognitive context.

Memory must be traversable according to purpose and required depth.

Higher Memory must not destroy the path toward deeper preserved
Experience and Evidence.

PCC-01 canonical boundaries remain mandatory:

Experience != Memory
Experience != Evidence
Memory does not replace Experience.
Interpretation != historical fact.
Persistence != authority.

PCC-04 already supplies SedimentedMemory.

RUN 001 therefore does NOT redesign Sedimentation and does NOT invent
another Memory product.

RUN 001 adds the structural anatomy required to organize accepted
SedimentedMemory into navigable depth.

REQUIRED PHYSIOLOGY

- stable layered-node identity;
- one node wraps one SedimentedMemory;
- structural depth;
- parent/child memory relationships;
- downward navigation;
- upward navigation;
- navigation from any node toward its roots;
- navigation from any node toward descendants;
- preservation of the SedimentedMemory provenance path;
- no raw Experience copied into layered Memory;
- no Evidence copied into layered Memory;
- no claim that structural depth equals truth or authority;
- no CSL implementation;
- no Progressive Recall implementation;
- no new Knowledge organ;
- no persistence backend in this RUN.

THIS RUN BUILDS ANATOMY, NOT THE COMPLETE PCC-05 ORGAN.
